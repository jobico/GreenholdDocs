// Writes THIRD-PARTY-NOTICES.md from package.json and package-lock.json.
// Usage: node scripts/generate-notices.mjs [--check]
// --check fails when the file is out of date. The script also fails when any
// package in the lockfile has a strong-copyleft licence (GPL, AGPL, SSPL, EUPL,
// CC-BY-SA); MPL and LGPL are allowed and listed. Unknown licences fail too.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));

const strong = /(^|[^L])GPL|AGPL|SSPL|EUPL|CC-BY-SA|CPAL|OSL-/i;
const weak = /LGPL|MPL|EPL|CDDL/i;

// Packages that declare no licence in package.json. Each was read by hand.
const reviewed = { 'khroma@2.1.0': 'MIT (licence file, reviewed)' };

const licenceOf = (entry, id) => {
  if (id && reviewed[id]) return reviewed[id];
  const l = entry.license ?? entry.licenses;
  if (!l) return 'UNKNOWN';
  return typeof l === 'string' ? l : Array.isArray(l) ? l.map((x) => x.type ?? x).join(' OR ') : (l.type ?? 'UNKNOWN');
};

const problems = [];
const weakList = [];
const counts = new Map();
for (const [path, entry] of Object.entries(lock.packages)) {
  if (!path) continue;
  const name = path.replace(/^.*node_modules\//, '');
  const lic = licenceOf(entry, `${name}@${entry.version}`);
  counts.set(lic, (counts.get(lic) ?? 0) + 1);
  // An OR expression is acceptable when one side is permissive.
  const options = lic.replace(/[()]/g, '').split(/\s+OR\s+/);
  const ok = options.some((o) => !strong.test(o) && o !== 'UNKNOWN');
  if (!ok) problems.push(`${name}@${entry.version}: ${lic}`);
  else if (options.every((o) => weak.test(o))) weakList.push(`${name}@${entry.version}: ${lic}`);
}

const rows = Object.keys(pkg.dependencies).sort().map((name) => {
  const entry = lock.packages[`node_modules/${name}`];
  const meta = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'));
  const url = typeof meta.repository === 'string' ? meta.repository : (meta.repository?.url ?? meta.homepage ?? '');
  return `| ${name} | ${entry.version} | ${licenceOf(entry)} | ${url.replace(/^git\+/, '').replace(/\.git$/, '')} |`;
});

const summary = [...counts.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`);

const text = `# Third-party notices

Generated by \`npm run notices\` from \`package.json\` and \`package-lock.json\`. Do not edit by hand.

## Direct dependencies

| Package | Version | Licence | Source |
|---|---|---|---|
${rows.join('\n')}

## Licences of all ${counts.size ? [...counts.values()].reduce((a, b) => a + b, 0) : 0} packages in the lockfile

| Licence | Packages |
|---|---|
${summary.join('\n')}

## Copyleft check

Strong copyleft licences (GPL, AGPL, SSPL, EUPL, CC-BY-SA) are refused: ${problems.length === 0 ? 'none found.' : 'FOUND, see the build output.'}
Weak copyleft licences (MPL, LGPL, EPL) are allowed because they are build tools only (sharp's libvips, lightningcss) and are not part of the published site: ${weakList.length === 0 ? 'none found.' : '\n\n' + weakList.map((w) => `- ${w}`).join('\n')}
`;

if (problems.length) {
  console.error('Refused licences:\n' + problems.join('\n'));
  process.exit(1);
}
const file = join(root, 'THIRD-PARTY-NOTICES.md');
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
    console.error('THIRD-PARTY-NOTICES.md is out of date. Run: npm run notices');
    process.exit(1);
  }
  console.log('THIRD-PARTY-NOTICES.md is up to date.');
} else {
  writeFileSync(file, text);
  console.log('Wrote THIRD-PARTY-NOTICES.md');
}
